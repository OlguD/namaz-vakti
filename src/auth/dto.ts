import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import { IsEmail, IsIn, IsOptional, IsString, Length, MaxLength, MinLength } from 'class-validator';

const lower = ({ value }: { value: unknown }) =>
  typeof value === 'string' ? value.trim().toLowerCase() : value;
const trim = ({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim() : value);

export class AnonymousLoginDto {
  @ApiPropertyOptional({ description: 'Stable per-install id generated by the app' })
  @IsOptional()
  @IsString()
  @Length(8, 128)
  installationId?: string;

  @ApiPropertyOptional({ enum: ['ios', 'android', 'web'] })
  @IsOptional()
  @IsIn(['ios', 'android', 'web'])
  platform?: 'ios' | 'android' | 'web';
}

export class AppleLoginDto {
  @ApiProperty({ description: 'identityToken from Sign in with Apple' })
  @IsString()
  @MaxLength(4096)
  identityToken: string;

  @ApiPropertyOptional({ description: 'Raw nonce the app passed (hashed) to Apple' })
  @IsOptional()
  @IsString()
  @MaxLength(256)
  nonce?: string;

  @ApiPropertyOptional({ description: 'Name Apple returned on first sign-in' })
  @IsOptional()
  @IsString()
  @Transform(trim)
  @MaxLength(24)
  displayName?: string;
}

export class GoogleLoginDto {
  @ApiProperty({ description: 'idToken from Google Sign-In' })
  @IsString()
  @MaxLength(4096)
  idToken: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @Transform(trim)
  @MaxLength(24)
  displayName?: string;
}

export class EmailRegisterDto {
  @ApiProperty({ example: 'ahmet@example.com' })
  @Transform(lower)
  @IsEmail()
  @MaxLength(254)
  email: string;

  @ApiProperty({ minLength: 8, maxLength: 128 })
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  password: string;

  @ApiProperty({ example: 'Ahmet' })
  @IsString()
  @Transform(trim)
  @Length(3, 24)
  displayName: string;
}

export class EmailLoginDto {
  @ApiProperty()
  @Transform(lower)
  @IsEmail()
  email: string;

  @ApiProperty()
  @IsString()
  @MaxLength(128)
  password: string;
}

export class TokenDto {
  @ApiProperty()
  @IsString()
  @MaxLength(512)
  token: string;
}

export class ForgotPasswordDto {
  @ApiProperty()
  @Transform(lower)
  @IsEmail()
  email: string;
}

export class ResetPasswordDto {
  @ApiProperty()
  @IsString()
  @MaxLength(512)
  token: string;

  @ApiProperty({ minLength: 8, maxLength: 128 })
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  password: string;
}

export class RefreshDto {
  @ApiPropertyOptional({
    description:
      'Native apps send it here. Web clients omit it; the httpOnly cookie is used instead.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(512)
  refreshToken?: string;
}

export class TokenPairDto {
  @ApiProperty() accessToken: string;
  @ApiProperty({ description: 'Seconds until the access token expires' })
  accessTokenExpiresIn: number;
  @ApiProperty() refreshToken: string;
  @ApiProperty() refreshTokenExpiresAt: string;
}

export class AuthResponseDto {
  @ApiProperty({ type: TokenPairDto }) tokens: TokenPairDto;
  @ApiProperty({ description: 'The signed-in user' }) user: Record<string, unknown>;
}
