import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  ParseIntPipe,
  ParseUUIDPipe,
  Post,
  Put,
  Query,
} from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiOperation,
  ApiProperty,
  ApiPropertyOptional,
  ApiTags,
} from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsIn, IsInt, IsOptional, IsString, MaxLength, Min, Max } from 'class-validator';
import { type AuthUser, CurrentUser, Public, RegisteredOnly } from '../auth/auth.decorators.js';
import { ChatBroadcaster } from './chat.broadcaster.js';
import { ChatService, MAX_MESSAGE_LENGTH, type ReportReason } from './chat.service.js';

const REASONS = [
  'spam',
  'harassment',
  'hate',
  'sexual',
  'violence',
  'misinformation',
  'other',
] as const;

class HistoryQuery {
  @ApiPropertyOptional({ description: 'Return messages older than this id' })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  before?: number;

  @ApiPropertyOptional({ minimum: 1, maximum: 100, default: 50 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit = 50;
}

class SendMessageDto {
  @ApiProperty({ maxLength: MAX_MESSAGE_LENGTH })
  @IsString()
  @MaxLength(MAX_MESSAGE_LENGTH * 2)
  body: string;

  @ApiPropertyOptional({ description: 'Idempotency key generated by the app' })
  @IsOptional()
  @IsString()
  @MaxLength(64)
  clientMessageId?: string;
}

class ReportDto {
  @ApiProperty({ enum: REASONS })
  @IsIn(REASONS)
  reason: ReportReason;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(500)
  note?: string;
}

@ApiTags('Chat')
@Controller({ version: '1' })
export class ChatController {
  constructor(
    private readonly chat: ChatService,
    private readonly broadcaster: ChatBroadcaster,
  ) {}

  @Public()
  @Get('chat/rooms')
  rooms() {
    return this.chat.rooms();
  }

  @Public()
  @Get('chat/rooms/:roomId/messages')
  @ApiOperation({
    summary: 'Message history, oldest first. Send a token to hide users you blocked.',
  })
  history(
    @Param('roomId') roomId: string,
    @Query() query: HistoryQuery,
    @CurrentUser() viewer?: AuthUser,
  ) {
    return this.chat.history(roomId, viewer?.id, query.before, query.limit);
  }

  @RegisteredOnly()
  @Post('chat/rooms/:roomId/messages')
  @ApiOperation({ summary: 'Send a message (REST alternative to the socket event)' })
  async send(
    @CurrentUser() user: AuthUser,
    @Param('roomId') roomId: string,
    @Body() body: SendMessageDto,
  ) {
    const message = await this.chat.send(user, roomId, body.body, body.clientMessageId);
    this.broadcaster.messageCreated(message);
    return message;
  }

  @ApiBearerAuth()
  @Delete('chat/messages/:id')
  @HttpCode(204)
  async remove(
    @CurrentUser() user: AuthUser,
    @Param('id', ParseIntPipe) id: number,
  ): Promise<void> {
    const { roomId } = await this.chat.delete(user, id);
    this.broadcaster.messageRemoved(roomId, String(id), 'deleted');
  }

  @ApiBearerAuth()
  @Post('chat/messages/:id/report')
  @HttpCode(204)
  @ApiOperation({ summary: 'Report a message; 3 distinct reports hide it until review' })
  async report(
    @CurrentUser() user: AuthUser,
    @Param('id', ParseIntPipe) id: number,
    @Body() body: ReportDto,
  ) {
    const result = await this.chat.report(user, id, body.reason, body.note);
    if (result.hidden) {
      this.broadcaster.messageRemoved(result.roomId, String(id), 'hidden');
    }
  }

  @ApiBearerAuth()
  @Get('me/blocks')
  blocks(@CurrentUser() user: AuthUser) {
    return this.chat.listBlocks(user.id);
  }

  @ApiBearerAuth()
  @Put('me/blocks/:userId')
  @HttpCode(204)
  @ApiOperation({ summary: 'Block a user: their messages disappear from history for you' })
  async block(
    @CurrentUser() user: AuthUser,
    @Param('userId', ParseUUIDPipe) userId: string,
  ): Promise<void> {
    await this.chat.block(user.id, userId);
  }

  @ApiBearerAuth()
  @Delete('me/blocks/:userId')
  @HttpCode(204)
  async unblock(
    @CurrentUser() user: AuthUser,
    @Param('userId', ParseUUIDPipe) userId: string,
  ): Promise<void> {
    await this.chat.unblock(user.id, userId);
  }
}
