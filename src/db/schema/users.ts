import { sql } from 'drizzle-orm';
import {
  boolean,
  index,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { districts } from './locations.js';

export const userKind = pgEnum('user_kind', ['anonymous', 'registered']);
export const userRole = pgEnum('user_role', ['user', 'moderator', 'admin']);
export const identityProvider = pgEnum('identity_provider', ['apple', 'google']);
export const emailTokenPurpose = pgEnum('email_token_purpose', ['verify_email', 'reset_password']);
export const devicePlatform = pgEnum('device_platform', ['ios', 'android', 'web']);

export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    kind: userKind('kind').notNull().default('anonymous'),
    role: userRole('role').notNull().default('user'),
    displayName: text('display_name'),
    email: text('email'),
    emailVerifiedAt: timestamp('email_verified_at', { withTimezone: true }),
    passwordHash: text('password_hash'),
    locale: text('locale').notNull().default('tr'),
    districtId: text('district_id').references(() => districts.id, { onDelete: 'set null' }),
    chatMutedUntil: timestamp('chat_muted_until', { withTimezone: true }),
    bannedUntil: timestamp('banned_until', { withTimezone: true }),
    lastSeenAt: timestamp('last_seen_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (t) => [
    // Emails are stored lower-cased; uniqueness only applies to accounts that have one.
    uniqueIndex('users_email_unique')
      .on(t.email)
      .where(sql`${t.email} is not null`),
    uniqueIndex('users_display_name_unique')
      .on(sql`lower(${t.displayName})`)
      .where(sql`${t.displayName} is not null`),
  ],
);

export const authIdentities = pgTable(
  'auth_identities',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    provider: identityProvider('provider').notNull(),
    subject: text('subject').notNull(),
    email: text('email'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex('auth_identities_provider_subject_unique').on(t.provider, t.subject),
    index('auth_identities_user_idx').on(t.userId),
  ],
);

/**
 * Refresh tokens rotate on every use. All tokens descended from one login share a
 * family; presenting an already-rotated token revokes the whole family (theft signal).
 */
export const refreshTokens = pgTable(
  'refresh_tokens',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    familyId: uuid('family_id').notNull(),
    tokenHash: text('token_hash').notNull(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    rotatedAt: timestamp('rotated_at', { withTimezone: true }),
    revokedAt: timestamp('revoked_at', { withTimezone: true }),
    userAgent: text('user_agent'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index('refresh_tokens_user_idx').on(t.userId),
    index('refresh_tokens_family_idx').on(t.familyId),
  ],
);

export const emailTokens = pgTable(
  'email_tokens',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    purpose: emailTokenPurpose('purpose').notNull(),
    tokenHash: text('token_hash').notNull(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    usedAt: timestamp('used_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex('email_tokens_hash_unique').on(t.tokenHash)],
);

export const devices = pgTable(
  'devices',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** Stable per-install identifier generated by the app. */
    installationId: text('installation_id').notNull(),
    platform: devicePlatform('platform').notNull(),
    pushToken: text('push_token'),
    locale: text('locale'),
    appVersion: text('app_version'),
    districtId: text('district_id').references(() => districts.id, { onDelete: 'set null' }),
    /** Push opt-ins. Prayer-time alerts are local notifications scheduled by the app. */
    liveAlerts: boolean('live_alerts').notNull().default(true),
    announcements: boolean('announcements').notNull().default(true),
    lastSeenAt: timestamp('last_seen_at', { withTimezone: true }).notNull().defaultNow(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex('devices_installation_unique').on(t.installationId),
    uniqueIndex('devices_push_token_unique')
      .on(t.pushToken)
      .where(sql`${t.pushToken} is not null`),
    index('devices_user_idx').on(t.userId),
  ],
);
